#!/usr/bin/env node
/**
 * Exports every copy string from the English dictionaries and markdown content
 * into docs/COPY.md, so the document and the site can never drift apart.
 * Requires Node >= 22.18 (native TypeScript type stripping).
 */
import { readFile, readdir, writeFile, mkdir } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { default: en } = await import(pathToFileURL(resolve(root, 'src/i18n/en/index.ts')).href);

const PAGES = [
  ['common', 'Site-wide: navigation, footer, cookie banner, labels'],
  ['home', 'Home'],
  ['capabilitiesIndex', 'Capabilities (index)'],
  ['capabilities', 'Capabilities (one page per area)'],
  ['engagementPage', 'Engagement models (page copy)'],
  ['engagementModels', 'Engagement models (the four models)'],
  ['caseStudies', 'Case studies (index)'],
  ['security', 'Security & IP protection'],
  ['team', 'Team'],
  ['insights', 'Insights (index)'],
  ['careers', 'Careers'],
  ['contact', 'Contact / Request an NDA call'],
  ['legal', 'Legal: privacy, terms, cookies'],
  ['misc', 'Thank-you and 404'],
];

const out = [];
const title = (s) => s.replace(/([A-Z])/g, ' $1').replace(/^./, (c) => c.toUpperCase()).trim();

function emit(value, depth, key) {
  const h = '#'.repeat(Math.min(depth, 6));
  if (typeof value === 'string') {
    out.push(key ? `**${title(key)}:** ${value}\n` : `${value}\n`);
  } else if (typeof value === 'function') {
    out.push(`**${title(key)}:** _(dynamic)_ \`${value.toString().replace(/\s+/g, ' ')}\`\n`);
  } else if (Array.isArray(value)) {
    if (value.every((v) => typeof v === 'string')) {
      out.push(key ? `**${title(key)}:**\n` : '');
      for (const v of value) out.push(`- ${v}`);
      out.push('');
    } else {
      if (key) out.push(`${h} ${title(key)}\n`);
      value.forEach((v, i) => {
        const name = v && typeof v === 'object' && (v.name || v.title || v.label || v.slug) ? `${i + 1}. ${v.name || v.title || v.label || v.slug}` : `Item ${i + 1}`;
        out.push(`${'#'.repeat(Math.min(depth + 1, 6))} ${name}\n`);
        emit(v, depth + 2, '');
      });
    }
  } else if (value && typeof value === 'object') {
    if (key) out.push(`${h} ${title(key)}\n`);
    for (const [k, v] of Object.entries(value)) emit(v, depth + 1, k);
  }
}

out.push('# Site copy (generated)\n');
out.push('Generated by `npm run docs` from `src/i18n/en/*.ts` and `src/content/**`. Do not edit by hand: change the source and regenerate.\n');
out.push('Placeholders use the form `[LABEL: note]`. See PLACEHOLDERS.md for the complete list.\n');

for (const [key, label] of PAGES) {
  out.push(`\n---\n\n## ${label}\n`);
  emit(en[key], 2, '');
}

for (const [folder, label] of [
  ['src/content/insights/en', 'Insights (articles)'],
  ['src/content/case-studies/en', 'Case studies (entries)'],
]) {
  out.push(`\n---\n\n## ${label}\n`);
  const dir = resolve(root, folder);
  for (const file of (await readdir(dir)).filter((f) => f.endsWith('.md')).sort()) {
    const md = await readFile(resolve(dir, file), 'utf8');
    out.push(`### ${file}\n`);
    out.push('```markdown');
    out.push(md.trim());
    out.push('```\n');
  }
}

await mkdir(resolve(root, 'docs'), { recursive: true });
await writeFile(resolve(root, 'docs/COPY.md'), out.join('\n'));
console.log('wrote docs/COPY.md');
