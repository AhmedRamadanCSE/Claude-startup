#!/usr/bin/env node
/**
 * Scans the source tree for [LABEL: note] placeholders and writes
 * docs/PLACEHOLDERS.md grouped by page. Also used by lint-placeholders.mjs.
 */
import { readFile, readdir, writeFile, stat } from 'node:fs/promises';
import { resolve, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const RE = /\[([A-Z][A-Z0-9 /&'.\-]+?)(?::\s*([^\]]*))?\]/g;
const MUSTACHE = /\{\{\s*([A-Z_]+)[^}]*\}\}/g;

const SKIP = new Set(['src/lib/placeholders.ts', 'src/lib/rehype-placeholders.mjs', 'src/styles/base.css', 'README.md']);

const GROUPS = [
  [/^src\/site\.config\.ts$/, 'Site-wide (src/site.config.ts)'],
  [/^src\/i18n\/en\/common\.ts$/, 'Site-wide (navigation, footer)'],
  [/^src\/i18n\/en\/home\.ts$/, 'Home'],
  [/^src\/pages\/index\.astro$/, 'Home'],
  [/^src\/i18n\/en\/capabilities\.ts$/, 'Capabilities'],
  [/^src\/i18n\/en\/engagement\.ts$/, 'Engagement models'],
  [/^src\/i18n\/en\/caseStudies\.ts$/, 'Case studies'],
  [/^src\/content\/case-studies\//, 'Case studies (entries)'],
  [/^src\/i18n\/en\/security\.ts$/, 'Security & IP protection'],
  [/^src\/i18n\/en\/team\.ts$/, 'Team'],
  [/^src\/i18n\/en\/insights\.ts$/, 'Insights'],
  [/^src\/content\/insights\//, 'Insights (articles)'],
  [/^src\/i18n\/en\/careers\.ts$/, 'Careers'],
  [/^src\/i18n\/en\/contact\.ts$/, 'Contact'],
  [/^src\/i18n\/en\/legal\.ts$/, 'Legal (privacy, terms, cookies)'],
  [/^src\/i18n\/en\/misc\.ts$/, 'Thank-you and 404'],
  [/^src\/components\/graphics\//, 'Graphics (figure labels)'],
  [/^src\/pages\/og\//, 'Open Graph images'],
  [/^(\.env\.example|astro\.config\.mjs)$/, 'Configuration (.env)'],
];

async function walk(dir, acc = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const p = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      if (['node_modules', 'dist', '.astro', '.git', 'docs'].includes(entry.name)) continue;
      await walk(p, acc);
    } else if (/\.(ts|mjs|astro|md|json|webmanifest|example)$/.test(entry.name) || entry.name === '.env.example') {
      acc.push(p);
    }
  }
  return acc;
}

export async function collect() {
  const files = (await walk(root)).concat([resolve(root, '.env.example')]).filter((f, i, a) => a.indexOf(f) === i);
  const found = [];
  for (const file of files) {
    const rel = relative(root, file).split(sep).join('/');
    if (SKIP.has(rel) || rel.startsWith('scripts/')) continue;
    try {
      if (!(await stat(file)).isFile()) continue;
    } catch {
      continue;
    }
    const text = await readFile(file, 'utf8');
    const lines = text.split('\n');
    lines.forEach((line, i) => {
      for (const m of line.matchAll(RE)) found.push({ file: rel, line: i + 1, label: m[1].trim(), note: (m[2] ?? '').trim(), raw: m[0] });
      for (const m of line.matchAll(MUSTACHE)) found.push({ file: rel, line: i + 1, label: m[1], note: 'template variable', raw: m[0] });
    });
  }
  return found;
}

function groupOf(file) {
  for (const [re, name] of GROUPS) if (re.test(file)) return name;
  return `Other (${file})`;
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const found = await collect();
  const groups = new Map();
  for (const f of found) {
    const g = groupOf(f.file);
    if (!groups.has(g)) groups.set(g, new Map());
    const key = f.raw;
    const entry = groups.get(g).get(key) ?? { ...f, count: 0, locations: [] };
    entry.count += 1;
    if (entry.locations.length < 3) entry.locations.push(`${f.file}:${f.line}`);
    groups.get(g).set(key, entry);
  }

  const order = GROUPS.map((g) => g[1]).filter((v, i, a) => a.indexOf(v) === i);
  const sorted = [...groups.keys()].sort((a, b) => (order.indexOf(a) === -1 ? 99 : order.indexOf(a)) - (order.indexOf(b) === -1 ? 99 : order.indexOf(b)));

  const out = ['# Placeholders to fill before launch (generated)\n'];
  out.push(`Generated by \`npm run docs\`. ${found.length} placeholder occurrences, ${[...groups.values()].reduce((n, m) => n + m.size, 0)} distinct, across ${groups.size} groups.\n`);
  out.push('Convention: `[LABEL: note]`. Fill the value in the file and line shown; the highlight on the site disappears automatically. Run `node scripts/lint-placeholders.mjs --strict` to fail CI while any remain.\n');
  out.push('Labels in brief:\n');
  out.push('- `NUMBER`, `DATA RATE`, `NODE(S)`, `FREQUENCY`, `VOLTAGE`, `RANGE`: a measured or specified figure we will substantiate under NDA.');
  out.push('- `NAME`, `BIO`, `PHOTO`, `LINKEDIN URL`: team identity.');
  out.push('- `EMAIL`, `PHONE`, `ADDRESS`, `LEGAL ENTITY NAME`, `BRAND_NAME`: company identity.');
  out.push('- `CASE STUDY`, `CHALLENGE`, `OUR ROLE`, `RESULT`: anonymized case-study content approved by the client.');
  out.push('- `LEGAL REVIEW`, `JURISDICTION`, `VENUE`, `PROCESSOR`, `SUPERVISORY AUTHORITY`: items for counsel.');
  out.push('- `CALENDAR URL`, `SITE URL` and the `.env` keys: configuration.\n');

  for (const g of sorted) {
    const m = groups.get(g);
    out.push(`\n## ${g}\n`);
    out.push('| Placeholder | Note | Where | Count |');
    out.push('| --- | --- | --- | --- |');
    for (const e of [...m.values()].sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line)) {
      const esc = (s) => s.replace(/\|/g, '\\|');
      out.push(`| \`${esc(e.raw)}\` | ${esc(e.note) || '—'} | ${e.locations.map((l) => `\`${l}\``).join('<br>')}${e.count > e.locations.length ? ' …' : ''} | ${e.count} |`);
    }
  }
  await writeFile(resolve(root, 'docs/PLACEHOLDERS.md'), out.join('\n') + '\n');
  console.log(`wrote docs/PLACEHOLDERS.md (${found.length} occurrences)`);
}
